<?php

declare(strict_types=1);

namespace Noerd\Cms\Services;

use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use Noerd\Cms\Helpers\FieldHelper;
use Noerd\Cms\Models\Collection;
use Noerd\Cms\Models\Content;
use Noerd\Cms\Models\ContentElement;
use Noerd\Cms\Support\CmsLanguageCodes;
use Noerd\Contracts\MediaResolverContract;
use Noerd\Support\HtmlSanitizer;

/**
 * The content editor works on ONE document — running text with elements in
 * between — while the storage stays one `content_elements` row per block: the
 * running text between two elements is a `rich_text` row, every other element
 * its own row. This service translates between the two.
 *
 * The working document is a list of sections:
 *
 *     ['kind' => 'text',    'uid' => 'r12', 'id' => 12, 'text' => ['de' => '<p>…</p>']]
 *     ['kind' => 'element', 'uid' => 'r13', 'id' => 13, 'key' => 'image_block_1_column', 'data' => [...]]
 *
 * `uid` identifies a section across editor round trips (saved rows: `r{id}`,
 * new ones: generated by the editor), `id` is the row — never taken from the
 * client. The structure (order of the sections) is shared by every language,
 * the running text is per language.
 */
final class ContentDocumentService
{
    public const string TEXT_ELEMENT = 'rich_text';

    /** @var array<int, string> */
    private const array RICH_TEXT_TYPES = ['richText', 'translatableRichText'];

    /** @var array<int, string> */
    private const array TRANSLATABLE_TYPES = ['translatableText', 'translatableTextarea', 'translatableRichText'];

    /**
     * The working document of a content, built from its rows.
     *
     * @return list<array<string, mixed>>
     */
    public function load(?Content $content): array
    {
        if ($content === null || ! $content->exists) {
            return [];
        }

        $sections = [];
        $language = CmsLanguageCodes::defaultFor((int) $content->tenant_id);

        foreach ($content->elements()->get() as $element) {
            $data = is_array($element->data) ? $element->data : (json_decode((string) $element->data, true) ?: []);

            if ($element->element_key === self::TEXT_ELEMENT) {
                $text = $data['text'] ?? [];
                $sections[] = [
                    'kind' => 'text',
                    'uid' => 'r' . $element->id,
                    'id' => (int) $element->id,
                    'text' => is_array($text) ? array_map('strval', array_filter($text, 'is_scalar')) : [$language => (string) $text],
                ];

                continue;
            }

            $sections[] = [
                'kind' => 'element',
                'uid' => 'r' . $element->id,
                'id' => (int) $element->id,
                'key' => (string) $element->element_key,
                'data' => $data,
            ];
        }

        return $sections;
    }

    /**
     * Merge the editor's draft — the document as the editor shows it in one
     * language — into the working document.
     *
     * Sections are matched by uid; a text section lists the uids it absorbed
     * (two text sections joined after an element between them was removed),
     * whose texts in the OTHER languages are appended to it. An element is only
     * accepted with a key the content type may use, and only its YAML fields
     * are kept. Nothing of the client decides a row id.
     *
     * @param  list<array<string, mixed>>  $working
     * @param  array<int, mixed>  $draft
     * @param  array<int, string>  $allowedKeys  element keys the content type may use
     * @return list<array<string, mixed>>
     */
    public function apply(array $working, array $draft, string $language, array $allowedKeys): array
    {
        $byUid = [];
        foreach ($working as $section) {
            $byUid[$section['uid']] = $section;
        }

        $result = [];
        $seen = [];

        foreach ($draft as $item) {
            if (! is_array($item)) {
                continue;
            }

            $uid = $this->validUid($item['uid'] ?? null) ?? $this->newUid();

            if (isset($seen[$uid])) {
                $uid = $this->newUid();
            }

            $seen[$uid] = true;
            $base = $byUid[$uid] ?? null;

            if (($item['kind'] ?? null) === 'text') {
                $section = ($base !== null && $base['kind'] === 'text')
                    ? $base
                    : ['kind' => 'text', 'uid' => $uid, 'id' => null, 'text' => []];

                foreach ((array) ($item['absorbed'] ?? []) as $absorbedUid) {
                    $absorbed = is_string($absorbedUid) ? ($byUid[$absorbedUid] ?? null) : null;

                    if ($absorbed === null || $absorbed['kind'] !== 'text' || $absorbedUid === $uid) {
                        continue;
                    }

                    foreach ($absorbed['text'] as $code => $html) {
                        if ($code !== $language && $html !== '') {
                            $section['text'][$code] = mb_trim(($section['text'][$code] ?? '') . $html);
                        }
                    }

                    unset($byUid[$absorbedUid]);
                }

                $section['text'][$language] = HtmlSanitizer::sanitize(is_string($item['html'] ?? null) ? $item['html'] : '');
                $result[] = $section;

                continue;
            }

            $key = is_string($item['key'] ?? null) ? $item['key'] : '';

            // A new element needs a key the content type may pick; an element
            // the document already holds keeps its key even when it is not
            // offered any more (a retired element, another type's element).
            $known = $base !== null && $base['kind'] === 'element' && $base['key'] === $key;

            if ($key === self::TEXT_ELEMENT || (! $known && ! in_array($key, $allowedKeys, true))) {
                continue;
            }

            $section = ($base !== null && $base['kind'] === 'element' && $base['key'] === $key)
                ? $base
                : ['kind' => 'element', 'uid' => $uid, 'id' => null, 'key' => $key, 'data' => []];

            $section['data'] = $this->normalizeData($key, is_array($item['data'] ?? null) ? $item['data'] : [], $section['data']);
            $result[] = $section;
        }

        return $result;
    }

    /**
     * The sections as the editor shows them in one language.
     *
     * @param  list<array<string, mixed>>  $working
     * @return list<array<string, mixed>>
     */
    public function forEditor(array $working, string $language): array
    {
        return array_map(fn(array $section): array => $section['kind'] === 'text'
            ? ['kind' => 'text', 'uid' => $section['uid'], 'html' => (string) ($section['text'][$language] ?? '')]
            : ['kind' => 'element', 'uid' => $section['uid'], 'saved' => $section['id'] !== null, 'key' => $section['key'], 'data' => (object) $section['data']], $working);
    }

    /**
     * Preview URLs of every media id the elements' image fields hold.
     *
     * @param  list<array<string, mixed>>  $working
     * @return array<int|string, string>
     */
    public function mediaPreviews(array $working): array
    {
        $resolver = app(MediaResolverContract::class);
        $previews = [];

        foreach ($working as $section) {
            if ($section['kind'] !== 'element') {
                continue;
            }

            foreach ($this->fieldsOf($section['key']) as $field) {
                $value = $section['data'][$this->fieldKey($field)] ?? null;

                if (($field['type'] ?? null) === 'image' && $value !== null && $value !== '') {
                    $preview = is_numeric($value) ? $resolver->getPreviewUrl((int) $value) : (string) $value;

                    if ($preview !== null) {
                        $previews[(string) $value] = $preview;
                    }
                }
            }
        }

        return $previews;
    }

    /**
     * Entry counts of the element collections of the saved elements, keyed by
     * section uid and field.
     *
     * @param  list<array<string, mixed>>  $working
     * @return array<string, array<string, int>>
     */
    public function collectionCounts(array $working): array
    {
        $service = app(ElementCollectionService::class);
        $counts = [];

        foreach ($working as $section) {
            if ($section['kind'] !== 'element' || $section['id'] === null) {
                continue;
            }

            foreach ($this->fieldsOf($section['key']) as $field) {
                if (($field['type'] ?? null) !== 'element-collection') {
                    continue;
                }

                $collection = Collection::query()
                    ->where('collection_key', $service->keyFor(ElementCollectionService::OWNER_ELEMENT_PAGE, (int) $section['id'], $this->fieldKey($field)))
                    ->where('is_element_collection', true)
                    ->first();

                $counts[$section['uid']][$this->fieldKey($field)] = (int) ($collection?->rows()->count() ?? 0);
            }
        }

        return $counts;
    }

    /**
     * Write the working document into the content's rows: the position is the
     * sort, text sections that are empty in every language are not stored,
     * rows no longer in the document are deleted through the model (so their
     * element collections go with them). Returns the document with the ids of
     * the rows it created — uids stay as they are.
     *
     * @param  list<array<string, mixed>>  $working
     * @return list<array<string, mixed>>
     */
    public function persist(Content $content, array $working): array
    {
        return DB::transaction(function () use ($content, $working): array {
            $existing = ContentElement::query()->where('content_id', $content->getKey())->get()->keyBy('id');
            $keep = [];
            $sort = 0;
            $result = [];

            foreach ($working as $section) {
                if ($section['kind'] === 'text') {
                    $text = array_map(fn($html): string => HtmlSanitizer::sanitize((string) $html), $section['text']);

                    if (! $this->hasText($text)) {
                        $section['id'] = null;
                        $result[] = $section;

                        continue;
                    }

                    $attributes = ['element_key' => self::TEXT_ELEMENT, 'data' => ['text' => $text]];
                } else {
                    $attributes = ['element_key' => $section['key'], 'data' => $this->normalizeData($section['key'], $section['data'], [])];
                }

                $sort++;
                $row = $section['id'] !== null ? $existing->get($section['id']) : null;

                if ($row !== null) {
                    $row->forceFill($attributes + ['sort' => $sort])->save();
                } else {
                    $row = ContentElement::create($attributes + ['content_id' => $content->getKey(), 'sort' => $sort]);
                }

                $keep[] = $row->id;
                $section['id'] = (int) $row->id;
                $result[] = $section;
            }

            $existing->except($keep)->each->delete();

            return $result;
        });
    }

    /**
     * The elements a content type may use, shaped for the editor: translated
     * labels, flattened fields with their options and defaults.
     *
     * @return list<array<string, mixed>>
     */
    public function catalog(string $contentType): array
    {
        $catalog = [];

        foreach (FieldHelper::getAllElementsGrouped($contentType) as $elements) {
            foreach ($elements as $element) {
                if ($element->element_key !== self::TEXT_ELEMENT) {
                    $catalog[] = $this->definition($element->element_key);
                }
            }
        }

        return $catalog;
    }

    /**
     * The editor definition of one element — also for an element the content
     * type does not offer, so a block the document already holds can be shown.
     *
     * @return array<string, mixed>
     */
    public function definition(string $key): array
    {
        $yaml = FieldHelper::getElementFields($key) ?? [];

        return [
            'key' => $key,
            'title' => __((string) (($yaml['title'] ?? '') ?: ucwords(str_replace('_', ' ', $key)))),
            'description' => __((string) ($yaml['description'] ?? '')),
            'group' => __((string) ($yaml['group'] ?? 'General')),
            'known' => $yaml !== [],
            'fields' => array_map(fn(array $field): array => $this->editorField($field), $this->fieldsOf($key)),
        ];
    }

    /**
     * @return array<int, string>
     */
    public function allowedKeys(string $contentType): array
    {
        return array_column($this->catalog($contentType), 'key');
    }

    /**
     * Keep only the element's YAML fields and give every value the shape of
     * its type; rich text is sanitized. Element collections are rows of their
     * own and never part of the data. Values of a key the client did not send
     * are taken from $previous.
     *
     * @param  array<string, mixed>  $data
     * @param  array<string, mixed>  $previous
     * @return array<string, mixed>
     */
    public function normalizeData(string $key, array $data, array $previous): array
    {
        $normalized = [];

        foreach ($this->fieldsOf($key) as $field) {
            $type = (string) ($field['type'] ?? 'text');
            $name = $this->fieldKey($field);

            if ($name === '' || in_array($type, ['element-collection', 'spacer'], true)) {
                continue;
            }

            $value = array_key_exists($name, $data) ? $data[$name] : ($previous[$name] ?? null);

            if (in_array($type, self::TRANSLATABLE_TYPES, true)) {
                $map = [];
                foreach (is_array($value) ? $value : [] as $code => $text) {
                    if (is_string($code) && is_scalar($text)) {
                        $map[$code] = $type === 'translatableRichText' ? HtmlSanitizer::sanitize((string) $text) : (string) $text;
                    }
                }
                $normalized[$name] = $map;

                continue;
            }

            $normalized[$name] = match (true) {
                $type === 'checkbox' => (bool) $value,
                $type === 'image' => is_numeric($value) ? (int) $value : (is_string($value) && $value !== '' ? $value : null),
                in_array($type, self::RICH_TEXT_TYPES, true) => HtmlSanitizer::sanitize(is_scalar($value) ? (string) $value : ''),
                default => is_scalar($value) ? (string) $value : ($field['default'] ?? ''),
            };
        }

        return $normalized;
    }

    /**
     * @param  array<string, string>  $text
     */
    private function hasText(array $text): bool
    {
        foreach ($text as $html) {
            if (mb_trim(strip_tags($html, '<hr><img>')) !== '') {
                return true;
            }
        }

        return false;
    }

    /**
     * @return list<array<string, mixed>>
     */
    private function fieldsOf(string $key): array
    {
        return array_values(FieldHelper::flattenFields(FieldHelper::getElementFields($key)['fields'] ?? []));
    }

    /**
     * @param  array<string, mixed>  $field
     */
    private function fieldKey(array $field): string
    {
        return (string) preg_replace('/^\w+\./', '', (string) ($field['name'] ?? ''));
    }

    /**
     * @param  array<string, mixed>  $field
     * @return array<string, mixed>
     */
    private function editorField(array $field): array
    {
        $options = [];
        foreach ((array) ($field['options'] ?? []) as $value => $option) {
            $options[] = is_array($option)
                ? ['value' => (string) ($option['value'] ?? ''), 'label' => __((string) ($option['label'] ?? $option['value'] ?? ''))]
                : ['value' => (string) $value, 'label' => __((string) $option)];
        }

        return [
            'name' => $this->fieldKey($field),
            'label' => __((string) ($field['label'] ?? '')),
            'type' => (string) ($field['type'] ?? 'text'),
            'colspan' => max(1, min(12, (int) ($field['colspan'] ?? 12))),
            'options' => $options,
            'placeholder' => isset($field['placeholder']) ? __((string) $field['placeholder']) : null,
            'default' => $field['default'] ?? null,
            'rowFields' => $field['fields'] ?? [],
        ];
    }

    private function validUid(mixed $uid): ?string
    {
        return is_string($uid) && preg_match('/^[A-Za-z0-9_-]{1,64}$/', $uid) ? $uid : null;
    }

    private function newUid(): string
    {
        return 'n' . Str::lower(Str::random(12));
    }
}
